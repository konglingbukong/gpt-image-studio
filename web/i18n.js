function pickLang() {
  let s = null;
  try { s = JSON.parse(localStorage.getItem("gi2_lang") || "null"); } catch (e) {}
  if (s && DICT[s]) return s;
  for (const l of navigator.languages || [navigator.language || "en"]) {
    const c = String(l).toLowerCase().slice(0, 2);
    if (DICT[c]) return c;
  }
  return "en";
}
let LANG = pickLang();

function t(key, vars) {
  let s = (DICT[LANG] && DICT[LANG][key]);
  if (s == null) s = DICT.en[key];
  if (s == null) return key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
  return s;
}

function applyI18n(root = document) {
  document.documentElement.lang = LANG === "zh" ? "zh-CN" : LANG;
  root.querySelectorAll("[data-i18n]").forEach(e => { e.textContent = t(e.dataset.i18n); });
  root.querySelectorAll("[data-i18n-html]").forEach(e => { e.innerHTML = t(e.dataset.i18nHtml); });
  root.querySelectorAll("[data-i18n-ph]").forEach(e => { e.placeholder = t(e.dataset.i18nPh); });
  root.querySelectorAll("[data-i18n-title]").forEach(e => { e.title = t(e.dataset.i18nTitle); });
  document.title = t("brand");
}

function setLang(l) {
  if (!DICT[l]) return;
  LANG = l;
  try { localStorage.setItem("gi2_lang", JSON.stringify(l)); } catch (e) {}
}
